'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {ActionRowBuilder,ButtonBuilder,ButtonStyle,AttachmentBuilder} = require('discord.js');
const source = fs.readFileSync(require('node:path').join(__dirname,'../bot.js'),'utf8');
const start = source.indexOf('function buildWarOverrideBulkPastePreview(session){');
assert.ok(start >= 0);
const context = vm.createContext({ActionRowBuilder,ButtonBuilder,ButtonStyle,AttachmentBuilder,Buffer});
vm.runInContext(source.slice(start,source.indexOf('\n}',start)+2),context);
const records = Array.from({length:30},(_,i)=>Object.freeze({club:`FoW Test Club ${i+1}`,elo:6000,president:'Test President',isolated:true,warStatus:'WAR_ACTIVE'}));
const session = Object.freeze({id:'test',records:Object.freeze(records),missing:Object.freeze([])});
const before = JSON.stringify(session);
const full = context.buildWarOverrideBulkPastePreview(session);
assert.ok(full.content.length <= 2000);
assert.equal(full.files.length,1);
const attachment = full.files[0].attachment.toString('utf8');
for (const r of records) assert.ok(attachment.includes(`**${r.club} (${r.elo})**`));
assert.equal(full.components[0].toJSON().components[0].custom_id,'war_override_bulk_confirm:test');
assert.equal(JSON.stringify(session),before);
const short = context.buildWarOverrideBulkPastePreview({...session,records:records.slice(0,1)});
assert.ok(!short.files);
assert.ok(short.content.includes('FoW Test Club 1'));
const missing = context.buildWarOverrideBulkPastePreview({...session,records:[],missing:Array.from({length:100},(_,i)=>`Unknown club ${i}`)});
assert.ok(missing.content.length<=2000);
assert.equal(missing.components[0].toJSON().components[0].disabled,true);
assert.ok(missing.files[0].attachment.toString('utf8').includes('Unknown club 99'));
console.log('PASS: long preview preserves all 30 clubs, short preview unchanged, missing list retained, no state mutation');
